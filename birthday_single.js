console.log(`上卦=(1998+2+3)%8=${s1%8} → ${up.sym}${up.name}(${up.num})  下卦=(1998+2+3+6)%8=${s2%8} → ${lo.sym}${lo.name}(${lo.num})`);
console.log(`卦象：${up.sym}${lo.sym}  ${guaName} · 动爻${dongYao}`);
console.log(`卦辞大意：大有卦“元亨”，火在天上、顺天休命，大有所得。`);
